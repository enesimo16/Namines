    /// </summary>
    private static string SchemaMetadata(IReadOnlyList<TableMetadata> metadata)
    {
        var payload = metadata.Select(m => new
        {
            name = m.Table.Name,
            pattern = m.Pattern.ToString().ToLowerInvariant(),
            primaryKey = m.PrimaryKey?.Name,
            labelColumn = m.LabelColumn?.Name,
            columns = m.Table.Columns.Select(c => new
            {
                name = c.Name,
                widget = ConsoleMetadata.Widget(c),
                nullable = c.IsNullable,
                isPrimaryKey = c.IsPK,
                // Değeri veritabanı üretiyorsa kullanıcıdan istemenin anlamı yok.
                // G40'ta bu bilgi modelde YOKTU ve form "anahtarı boş bırak"
                // diye yazılı bir nota mecbur kalmıştı; artık form biliyor.
                isGenerated = IdentityPolicy.IsGenerated(m.Table, c),
                maxLength = c.Length,
            }),
        });

        var json = JsonSerializer.Serialize(payload, new JsonSerializerOptions { WriteIndented = true });

        return $$"""
        // Generated by Namines. Do not edit by hand.

        export interface ConsoleColumn {
          name: string;
          widget: string;
          nullable: boolean;
          isPrimaryKey: boolean;
          /** The database assigns this value; the form does not ask for it. */
          isGenerated: boolean;
          maxLength: number | null;
        }

        export interface ConsoleTable {
          name: string;
          pattern: "crud" | "junction" | "tree" | "readonly";
          primaryKey: string | null;
          labelColumn: string | null;
          columns: ConsoleColumn[];
        }

        export const tables: ConsoleTable[] = {{json}};

        export function findTable(name: string): ConsoleTable | undefined {
          return tables.find((t) => t.name === name);
        }

        """;
    }

    private static string GatewayClient() => """
        // Generated by Namines. Do not edit by hand.
        //
        // Server-only: this module reads NAMINES_API_KEY. Importing it from a client
        // component would ship the key to the browser, so it is marked accordingly.
        import "server-only";

        const baseUrl = process.env.NAMINES_API_URL ?? "http://localhost:5000";
        const apiKey = process.env.NAMINES_API_KEY ?? "";

        export interface ListResult<T> {
          rows: T[];
          page: number;
          pageSize: number;
          totalCount: number;
        }

        /**
         * The Gateway wraps every row as `{ values: { ... } }` so it can add row-level
         * metadata later without breaking clients. The console does not need that
         * envelope, and unwrapping it here — rather than in each page — keeps the
         * shape in one place.
         */
        interface WrappedRow<T> {
          values: T;
        }

        async function call<T>(path: string, body: unknown): Promise<T> {
          if (!apiKey) {
            throw new Error(
              "NAMINES_API_KEY is not set. Copy .env.example to .env.local and fill it in."
            );
          }

          const response = await fetch(`${baseUrl}/api/gateway/${path}`, {
            method: "POST",
            headers: {
              "Content-Type": "application/json",
              "X-Namines-Key": apiKey,
            },
            body: JSON.stringify(body),
            // Admin console: always show current data, never a cached page.
            cache: "no-store",
          });

          if (!response.ok) {
            // The Gateway explains refusals precisely (permission, rate limit,
            // origin). Passing the message through is more useful than a generic
            // "request failed".
            const detail = await response.text();
            throw new Error(`Gateway ${response.status}: ${detail}`);
          }

          return (await response.json()) as T;
        }

        /**
         * The connection string lives on this server, not in Namines: the Gateway
         * needs it per request. Keep it beside the API key.
         */
        function connection() {
          const value = process.env.NAMINES_DB_CONNECTION;
          if (!value) {
            throw new Error(
              "NAMINES_DB_CONNECTION is not set. It is the connection string the Gateway uses."
            );
          }
          return value;
        }

        export async function listRows<T>(
          tableName: string,
          page = 1,
          pageSize = 25,
          orderByColumn?: string | null
        ): Promise<ListResult<T>> {
          const result = await call<ListResult<WrappedRow<T>>>("list", {
            connectionString: connection(),
            dbType: process.env.NAMINES_DB_TYPE ?? "PostgreSQL",
            tableName,
            page,
            pageSize,
            orderByColumn,
          });

          return { ...result, rows: result.rows.map((row) => row.values) };
        }

        export async function detailRow<T>(
          tableName: string,
          pkColumn: string,
          pkValue: string
        ): Promise<T | null> {
          const result = await call<WrappedRow<T> | null>("detail", {
            connectionString: connection(),
            dbType: process.env.NAMINES_DB_TYPE ?? "PostgreSQL",
            tableName,
            pkColumn,
            pkValue,
          });

          return result ? result.values : null;
        }

        /**
         * Values are sent as strings; `null` means SQL NULL. The Gateway binds them
         * as parameters, so nothing here is concatenated into SQL.
         */
        export function createRow(tableName: string, values: Record<string, string | null>) {
          return call<Record<string, unknown>>("create", {
            connectionString: connection(),
            dbType: process.env.NAMINES_DB_TYPE ?? "PostgreSQL",
            tableName,
            values,
          });
        }

        export function updateRow(
          tableName: string,
          pkColumn: string,
          pkValue: string,
          values: Record<string, string | null>
        ) {
          return call<{ affectedRows: number }>("update", {
            connectionString: connection(),
            dbType: process.env.NAMINES_DB_TYPE ?? "PostgreSQL",
            tableName,
            pkColumn,
            pkValue,
            values,
          });
        }

        export function deleteRow(tableName: string, pkColumn: string, pkValue: string) {
          return call<{ affectedRows: number }>("delete", {
            connectionString: connection(),
            dbType: process.env.NAMINES_DB_TYPE ?? "PostgreSQL",
            tableName,
            pkColumn,
            pkValue,
          });
        }

        """;

