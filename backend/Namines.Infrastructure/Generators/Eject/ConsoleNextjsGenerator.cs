                    color: "#7f1d1d",
                    padding: 12,
                    borderRadius: 6,
                    fontSize: 13,
                    whiteSpace: "pre-wrap",
                  }}
                >
                  {state.error}
                </pre>
              )}

              {table.columns
                .filter((column) => !(creating && column.isGenerated))
                .map((column) => (
                <div key={column.name} style={{ marginBottom: 14 }}>
                  <label
                    htmlFor={column.name}
                    style={{ display: "block", fontSize: 13, marginBottom: 4, color: "#374151" }}
                  >
                    {column.name}
                    {!column.nullable && !column.isPrimaryKey && (
                      <span style={{ color: "#b91c1c" }} aria-hidden="true">
                        {" *"}
                      </span>
                    )}
                    {column.isPrimaryKey && (
                      <span style={{ color: "#6b7280", fontSize: 12 }}> (key)</span>
                    )}
                  </label>
                  <Field
                    column={column}
                    initial={initial ? initial[column.name] : undefined}
                    readOnly={column.isPrimaryKey && initial !== undefined}
                  />
                </div>
              ))}

              <button
                type="submit"
                disabled={pending}
                style={{
                  padding: "8px 16px",
                  fontSize: 14,
                  borderRadius: 6,
                  border: "1px solid #111827",
                  background: pending ? "#6b7280" : "#111827",
                  color: "#ffffff",
                  cursor: pending ? "progress" : "pointer",
                }}
              >
                {pending ? "Saving..." : submitLabel}
              </button>
            </form>
          );
        }

        /**
         * On an existing row the key is shown but not editable: it is how the Gateway
         * finds the row being changed. Editing it here would describe two different
         * rows in one request.
         */
        function Field({
          column,
          initial,
          readOnly,
        }: {
          column: ConsoleColumn;
          initial: unknown;
          readOnly: boolean;
        }) {
          const value = initial === null || initial === undefined ? "" : String(initial);
          const style = readOnly ? { ...field, background: "#f3f4f6", color: "#6b7280" } : field;

          if (column.widget === "boolean") {
            // Uc secenek, checkbox degil: nullable bir boolean'da "bos" ile "false"
            // farkli seyler ve checkbox ikisini ayirt edemez.
            return (
              <select
                id={column.name}
                name={column.name}
                defaultValue={value}
                disabled={readOnly}
                style={style}
              >
                {column.nullable && <option value="">(null)</option>}
                <option value="true">true</option>
                <option value="false">false</option>
              </select>
            );
          }

          if (column.widget === "textarea") {
            return (
              <textarea
                id={column.name}
                name={column.name}
                defaultValue={value}
                readOnly={readOnly}
                rows={4}
                style={style}
              />
            );
          }

          return (
            <input
              id={column.name}
              name={column.name}
              defaultValue={value}
              readOnly={readOnly}
              type={column.widget}
              maxLength={column.maxLength ?? undefined}
              // required DEGIL: bos birakilan bir anahtar, veritabaninin anahtari
              // kendisinin uretmesi anlamina geliyor. Tarayicida zorunlu kilmak,
              // otomatik anahtarli tabloya satir eklemeyi imkansizlastirirdi.
              required={!column.nullable && !column.isPrimaryKey}
              style={style}
            />
          );
        }

        """;

    private static string DeleteButtonComponent() => """
        // Generated by Namines. Do not edit by hand.
        "use client";

        import { useState, useTransition } from "react";

        /**
         * Deleting asks first, and the question names the row.
         *
         * A one-click delete in a console that talks to a live database is a data-loss
         * default, and there is no undo behind it -- the Gateway runs a real DELETE.
         * The confirmation repeats the table and key so a mis-click on the wrong row
         * is visible before it happens, not after.
         */
        export default function DeleteButton({
          tableName,
          pkValue,
          action,
        }: {
          tableName: string;
          pkValue: string;
          action: () => Promise<{ error: string | null }>;
        }) {
          const [asking, setAsking] = useState(false);
          const [error, setError] = useState<string | null>(null);
          const [pending, startTransition] = useTransition();

          if (!asking) {
            return (
              <button
                type="button"
                onClick={() => setAsking(true)}
                style={{
                  padding: "8px 16px",
                  fontSize: 14,
                  borderRadius: 6,
                  border: "1px solid #b91c1c",
                  background: "transparent",
                  color: "#b91c1c",
                  cursor: "pointer",
                }}
              >
                Delete
              </button>
            );
          }

          return (
            <div style={{ fontSize: 13 }}>
              <p style={{ margin: "0 0 8px", color: "#7f1d1d" }}>
                Delete <strong>{pkValue}</strong> from <strong>{tableName}</strong>? This cannot be
                undone.
              </p>
              {error && (
                <pre style={{ color: "#7f1d1d", whiteSpace: "pre-wrap", fontSize: 13 }}>{error}</pre>
              )}
              <button
                type="button"
                disabled={pending}
                onClick={() =>
                  startTransition(async () => {
                    const result = await action();
                    // Silme basariliysa action yonlendirir ve buraya hic donulmez;
                    // buraya donmek, islemin BASARISIZ oldugu anlamina gelir.
                    if (result?.error) setError(result.error);
