                  cursor: pending ? "progress" : "pointer",
                  marginRight: 8,
                }}
              >
                {pending ? "Deleting..." : "Yes, delete"}
              </button>
              <button
                type="button"
                onClick={() => setAsking(false)}
                style={{
                  padding: "6px 12px",
                  fontSize: 13,
                  borderRadius: 6,
                  border: "1px solid #d1d5db",
                  background: "transparent",
                  cursor: "pointer",
                }}
              >
                Cancel
              </button>
