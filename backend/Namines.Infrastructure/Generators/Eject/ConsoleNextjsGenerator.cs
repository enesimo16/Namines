    /// <summary>
    /// Yazma yolu Server Action olarak uretiliyor, istemciden cagrilan bir API
    /// route olarak DEGIL.
    ///
    /// <b>Sebep API anahtari.</b> Panelin anahtari yalnizca sunucuda duruyor; yazma
    /// islemini tarayicidan yapmak, ya anahtari tarayiciya indirmek ya da anahtari
    /// koruyan ikinci bir uc yazmak demekti. Server Action ikisini de gerektirmiyor:
    /// form dogrudan sunucudaki fonksiyona gidiyor.
    /// </summary>
    private static string ServerActions() => """
        // Generated by Namines. Do not edit by hand.
        "use server";

        import { revalidatePath } from "next/cache";
        import { redirect } from "next/navigation";
        import { findTable, type ConsoleTable } from "../lib/schema";
        import { createRow, updateRow, deleteRow } from "../lib/gateway";

        export interface FormState {
          error: string | null;
        }

        /**
         * Reads a submitted form into the value map the Gateway expects.
         *
         * An empty input on a **nullable** column becomes SQL NULL, not "". If both
         * became "", a nullable column could never be cleared once it held a value --
         * and clearing a field is one of the things an admin console exists for. The
         * cost: a nullable text column cannot be set to an empty string from this
         * form. That is the rarer need, and the README says so.
         *
         * The primary key is excluded on update: the key identifies which row to
         * change, so allowing it in the same payload would let one field mean two
         * different things at once.
         */
        function readValues(
          table: ConsoleTable,
          form: FormData,
          options: { includePrimaryKey: boolean }
        ): Record<string, string | null> {
          const values: Record<string, string | null> = {};

          for (const column of table.columns) {
            if (column.isPrimaryKey && !options.includePrimaryKey) continue;

            const raw = form.get(column.name);
            if (raw === null) continue;

            const text = String(raw);

            if (text === "") {
              // Bos birakilmis birincil anahtar GONDERILMIYOR: modelden anahtarin
              // veritabani tarafindan uretilip uretilmedigini bilemiyoruz. Bos dize
              // gondermek, otomatik anahtarli bir tabloda anlasilmaz bir hatayla
              // duserdi; alani hic gondermemek veritabaninin yapilandirildigi seyi
              // yapmasina izin verir.
              if (column.isPrimaryKey) continue;
              values[column.name] = column.nullable ? null : "";
              continue;
            }

            values[column.name] = text;
          }

          return values;
        }

        function describe(error: unknown): string {
          return error instanceof Error ? error.message : String(error);
        }

        export async function createAction(
          tableName: string,
          _previous: FormState,
          form: FormData
        ): Promise<FormState> {
          const table = findTable(tableName);
          if (!table) return { error: `Unknown table: ${tableName}` };
          if (table.pattern === "readonly") {
            return { error: "This table has no primary key, so it cannot be edited." };
          }

          try {
            await createRow(table.name, readValues(table, form, { includePrimaryKey: true }));
          } catch (error) {
            return { error: describe(error) };
          }

          // redirect() bir istisna firlatarak calisir; try blogunun ICINDE cagrilsaydi
          // kendi catch'imiz onu bir hata sanip yonlendirmeyi yutardi.
          revalidatePath(`/${table.name}`);
          redirect(`/${table.name}`);
        }

        export async function updateAction(
          tableName: string,
          pkValue: string,
          _previous: FormState,
          form: FormData
        ): Promise<FormState> {
          const table = findTable(tableName);
          if (!table) return { error: `Unknown table: ${tableName}` };
          if (!table.primaryKey) {
            return { error: "This table has no single-column primary key, so it cannot be edited." };
          }

          try {
            await updateRow(
              table.name,
              table.primaryKey,
              pkValue,
              readValues(table, form, { includePrimaryKey: false })
            );
          } catch (error) {
            return { error: describe(error) };
          }

          revalidatePath(`/${table.name}`);
          redirect(`/${table.name}`);
        }

        export async function deleteAction(tableName: string, pkValue: string): Promise<FormState> {
          const table = findTable(tableName);
          if (!table) return { error: `Unknown table: ${tableName}` };
          if (!table.primaryKey) {
            return { error: "This table has no single-column primary key, so it cannot be edited." };
          }

          try {
            await deleteRow(table.name, table.primaryKey, pkValue);
          } catch (error) {
            return { error: describe(error) };
          }

          revalidatePath(`/${table.name}`);
          redirect(`/${table.name}`);
        }

        """;

